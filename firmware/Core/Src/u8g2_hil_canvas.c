void SetActiveFont(u8g2_t* u8g2_inst, const char* font_name) {
	// Compare word sent by python and select the correct font
	// Add entry here to enable a new font
	
	if (strcmp(font_name, "tiny") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_4x6_tr); 
	} 
	else if (strcmp(font_name, "small") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_5x8_tr); 
	}
	else if (strcmp(font_name, "standard") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_6x10_tr); 
	}
	else if (strcmp(font_name, "bold") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_ncenB08_tr); 
	}
	else if (strcmp(font_name, "title") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_helvB12_tr); 
	}
	else if (strcmp(font_name, "clock") == 0) {
		u8g2_SetFont(u8g2_inst, u8g2_font_logisoso24_tn); 
	}
}

void DrawIcon(u8g2_t* u8g2_inst, uint8_t x, uint8_t y, const char* icon_name) {
	// Add entry of custom icon here
	
  if (strcmp(icon_name, "wifi") == 0) {
		// u8g2_DrawXBM(u8g2, x, y, width, height, array)
		u8g2_DrawXBM(u8g2_inst, x, y, 8, 8, icon_wifi_8x8);
	} 
	else if (strcmp(icon_name, "battery") == 0) {
		u8g2_DrawXBM(u8g2_inst, x, y, 8, 8, icon_battery_8x8);
	}
	else if (strcmp(icon_name, "autobot") == 0) {
		u8g2_DrawXBM(u8g2_inst, x, y, 114, 64, autobot_symbol);
	}
}

void ProcessUARTPacket(uint8_t* rx_buffer, u8g2_t* u8g2_inst, UART_HandleTypeDef* huart) {
	uint8_t opcode = rx_buffer[0];
	uint8_t x      = rx_buffer[1];
	uint8_t y      = rx_buffer[2];
	uint8_t param1 = rx_buffer[3];
	uint8_t param2 = rx_buffer[4]; 
	uint8_t param3 = rx_buffer[5];
	uint8_t auto_render = rx_buffer[6];
	char* payload_str = (char*)&rx_buffer[8]; 
	
	switch (opcode) {
		case 0x01: // BOX
			u8g2_DrawBox(u8g2_inst, x, y, param1, param2);
			break;
		case 0x02: // CIRCLE 
			u8g2_DrawCircle(u8g2_inst, x, y, param1, U8G2_DRAW_ALL);
			break;
		case 0x03: // CLEAR
			u8g2_ClearBuffer(u8g2_inst);
			u8g2_SetFont(u8g2_inst, u8g2_font_6x10_tr);
			u8g2_SetFontDirection(u8g2_inst, 0);
			u8g2_SetDrawColor(u8g2_inst, 1);
			break;
		case 0x04: // TEXT
			u8g2_DrawStr(u8g2_inst, x, y, payload_str);
			break;						
		case 0x05: // SET FONT
			SetActiveFont(u8g2_inst, payload_str);
			break;
		case 0x06: // FRAME 
			u8g2_DrawFrame(u8g2_inst, x, y, param1, param2);
			break;
		case 0x07: // LINE
			u8g2_DrawLine(u8g2_inst, x, y, param1, param2);
			break;
		case 0x08: // DISC 
			u8g2_DrawDisc(u8g2_inst, x, y, param1, U8G2_DRAW_ALL);
			break;
		case 0x09: // RBOX 
			u8g2_DrawRBox(u8g2_inst, x, y, param1, param2, param3);
			break;
		case 0x0A: // RFRAME
			u8g2_DrawRFrame(u8g2_inst, x, y, param1, param2, param3);
			break;
		case 0x0B: // PIXEL
			u8g2_DrawPixel(u8g2_inst, x, y);
			break;
		case 0x0C: // SET ROTATION
			u8g2_SetFontDirection(u8g2_inst, param1);
			break;
		case 0x0D: // OP_RENDER
			break;
		case 0x0E: // OP_ICON
			DrawIcon(u8g2_inst, x, y, payload_str);
			break;
		case 0x0F: // DRAW_MODE 
			u8g2_SetDrawColor(u8g2_inst, param1);
			break;
		case 0x10: // OP_CONTRAST
			u8g2_SetContrast(u8g2_inst, param1);
			break;
		case 0x11: // OP_SLEEP
			u8g2_SetPowerSave(u8g2_inst, 1);
			break;
		case 0x12: // OP_WAKE
			u8g2_SetPowerSave(u8g2_inst, 0);
			break;
	}
	
	u8g2_SendBuffer(u8g2_inst);
	
	uint8_t ack_byte = 0xFF;
	HAL_UART_Transmit(huart, &ack_byte, 1, 10);
}